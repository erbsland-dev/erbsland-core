using namespace el::text::literals;

Manifest::Manifest(const frame::ProjectFiles &files, el::String toolName) :
    _toolName{std::move(toolName)}, _files{files} {
}

auto Manifest::hash(const Input &input) const -> el::ByteBlock {
    try {
        return _files.textChecksum(input.path, el::HashAlgorithm::Sha2_256);
    } catch (const el::ApplicationError &) {
        throw el::ApplicationError{
            "Security Hash Input Failed"_el, "The selected source could not be hashed."_el, std::current_exception()}
            .withSourcePath(input.relative);
    }
}

auto Manifest::hex(const el::ByteBlock &digest) -> el::String {
    static const auto cFormat = el::base_n::BaseNFormat{U"0123456789abcdef"_el};
    return el::base_n::BaseNEncoder{digest, cFormat}.toString();
}

void Manifest::field(el::Hasher &hasher, const el::String &text) {
    hasher.update(text);
    hasher.update("\0"_el);
}

auto Manifest::generate(
    const el::List<Input> &inputs, const unsigned int workers, const frame::TaskProgress &progress) const
    -> el::String {
    progress.beginPhase("Hashing source files"_el, inputs.count());
    auto digests = el::List<el::ByteBlock>{};
    if (!inputs.isEmpty()) {
        const auto count =
            static_cast<unsigned int>(std::min(inputs.count().toSizeT(), static_cast<std::size_t>(workers)));
        const auto pool = el::WorkerPool::create(el::WorkerPoolOptions{}.setWorkerCount(count));
        digests = pool->map(
                          inputs,
                          [this, &progress](const Input &input) -> el::ByteBlock {
                              auto result = hash(input);
                              progress.advance();
                              return result;
                          })
                      .get();
    }
    progress.beginPhase("Building security manifest"_el);
    auto directories = el::StringMap<el::Hasher>{};
    auto records = el::StringMap<el::String>{};
    for (auto index = el::ItemIndex{}; index.isWithin(inputs.count()); ++index) {
        const auto &input = inputs.getRef(index);
        const auto &digest = digests.getRef(index);
        if (input.directoryRecord) {
            const auto parent = input.path.parent().toRelativeOrThrow(_files.projectRoot()).toPosix();
            auto hasher = directories.take(parent);
            if (!hasher.isValid()) {
                hasher = el::Hasher{el::HashAlgorithm::Sha2_256};
                field(hasher, "directory"_el);
            }
            field(hasher, input.path.name());
            hasher.update(digest);
            hasher.update("\0"_el);
            directories.set(parent, std::move(hasher));
        }
        if (input.fileRecord) {
            auto hasher = el::Hasher{el::HashAlgorithm::Sha2_256};
            field(hasher, "file"_el);
            field(hasher, input.relative);
            hasher.update(digest);
            records.set(input.relative, hex(hasher.finalize()));
        }
    }
    for (const auto &[name, value] : directories) {
        auto hasher = value;
        records.set(el::join(name, "/"_el), hex(hasher.finalize()));
    }
    auto names = el::StringList{};
    for (const auto &[name, digest] : records) {
        names.append(name);
    }
    names.sort([](const el::String &left, const el::String &right) -> bool { return left.compareBinary(right) < 0; });
    auto total = el::Hasher{el::HashAlgorithm::Sha2_256};
    field(total, "security-hashes-v2"_el);
    auto lines = el::StringEditor{};
    for (const auto &name : names) {
        const auto digest = *records.get(name);
        field(total, name);
        field(total, digest);
        lines.append(name).append(" "_el).append(digest).append("\n"_el);
    }
    return el::join(
        "# Generated by "_el,
        _toolName,
        " security-hashes\n# Hash format: security-hashes-v2\n"
        "# Do not edit manually.\n\n* "_el,
        hex(total.finalize()),
        "\n"_el,
        el::String{lines});
}

auto Manifest::publish(const el::Path &output, const el::String &text, const bool verify) const -> bool {
    const auto path = _files.checked(output);
    if (path.info().exists() &&
        _files.textChecksum(path, el::HashAlgorithm::Sha2_256) ==
            frame::calculateTextChecksum(text, el::HashAlgorithm::Sha2_256)) {
        return false;
    }
    if (verify) {
        throw el::ApplicationError{
            "Security Hash Manifest Is Out of Date"_el,
            "The manifest is missing or differs. Run security-hashes without --verify to regenerate it."_el}
            .withSourcePath(path.toString());
    }
    try {
        path.content().replaceTextOrThrow(
            text,
            el::PathReplaceTextOptions{}.setBeforeCommit(
                [this](const el::Path &source, const el::Path &destination) -> void {
                    _files.checked(source);
                    _files.checked(destination);
                }));
    } catch (const el::PathError &) {
        throw el::ApplicationError{
            "Manifest Update Failed"_el,
            "The security hash manifest could not be replaced."_el,
            std::current_exception()}
            .withSourcePath(path.toString());
    }
    return true;
}

